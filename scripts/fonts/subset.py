#!/usr/bin/env python3
"""Regenerates committed web fonts; never runs during the application build."""

import hashlib
from copy import deepcopy
import io
import json
import shutil
import unicodedata
import urllib.request
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from positioning import positioning_core

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
ASSETS = ROOT / "web/src/lib/theme/assets"
FEATURES = {"calt", "ccmp", "clig", "curs", "kern", "liga", "locl", "mark", "mkmk", "rlig", "rclt", "tnum"}
CORE = set(range(0x20, 0x7F)) | {0x00A0, 0x00D7, 0x2010, 0x2011, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026, 0x21B5, 0x21E7, 0x2303, 0x2325, 0x232B, 0x238B}
FACES = [
    ("DepartureMono-1.500", "Departure Mono", "normal"),
    ("JetBrainsMono", "JetBrains Mono", "normal"),
    ("JetBrainsMono-Italic", "JetBrains Mono", "italic"),
    ("InterVariable", "Inter", "normal"),
    ("InterVariable-Italic", "Inter", "italic"),
]


def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][1] + 1:
            groups[-1][1] = point
        else:
            groups.append([point, point])
    return ", ".join(f"U+{a:04X}" if a == b else f"U+{a:04X}-{b:04X}" for a, b in groups)


def inventory(path):
    font = TTFont(path)
    hinted_glyphs = 0
    if "glyf" in font:
        hinted_glyphs = sum(bool(getattr(font["glyf"][name], "program", None) and font["glyf"][name].program.getBytecode()) for name in font["glyf"].keys())
    elif "CFF " in font:
        top = font["CFF "].cff.topDictIndex[0]
        for name in top.CharStrings.charStrings:
            charstring = top.CharStrings[name]
            charstring.decompile()
            hinted_glyphs += any(op in charstring.program for op in ("hstem", "vstem", "hstemhm", "vstemhm", "hintmask", "cntrmask"))
    return {
        "file": path.name,
        "bytes": path.stat().st_size,
        "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
        "glyphs": len(font.getGlyphOrder()),
        "characters": len(font.getBestCmap()),
        "unicodeRange": ranges(font.getBestCmap()),
        "axes": {a.axisTag: [a.minValue, a.defaultValue, a.maxValue] for a in font["fvar"].axes} if "fvar" in font else {},
        "features": {tag: sorted({r.FeatureTag for r in font[tag].table.FeatureList.FeatureRecord}) for tag in ("GSUB", "GPOS") if tag in font},
        "hintTables": [tag for tag in ("cvt ", "fpgm", "prep", "gasp") if tag in font],
        "hintTableBytes": {tag: len(font.getTableData(tag)) for tag in ("cvt ", "fpgm", "prep", "gasp") if tag in font},
        "hintedGlyphs": hinted_glyphs,
    }


def rename(font, family, style):
    # Renames every family/PostScript identifier, including variable-instance names.
    family = "Garcon " + family
    postscript = family.replace(" ", "") + ("Italic" if style == "italic" else "Regular")
    if "CFF " in font:
        cff = font["CFF "].cff
        cff.fontNames = [postscript]
        cff.topDictIndex[0].FullName = family + " " + style.title()
        cff.topDictIndex[0].FamilyName = family
    names = font["name"]
    for record in names.names:
        value = None
        if record.nameID in (1, 16, 21):
            value = family
        elif record.nameID in (3, 4):
            value = family + " " + style.title()
        elif record.nameID in (6, 25):
            value = postscript
        if value is not None:
            record.string = value.encode(record.getEncoding())
    if "fvar" in font:
        for instance in font["fvar"].instances:
            if instance.postscriptNameID != 65535:
                names.setName(postscript + str(instance.subfamilyNameID), instance.postscriptNameID, 3, 1, 0x409)


def main():
    messages = json.loads((ROOT / "web/messages/en.json").read_text())
    ui_points = {ord(char) for value in messages.values() if isinstance(value, str) for char in value}
    for source in json.loads((HERE / "sources.json").read_text()):
        path = HERE / "sources" / source["file"]
        if not path.exists():
            with urllib.request.urlopen(source["url"]) as response:
                data = response.read()
            if hashlib.sha256(data).hexdigest() != source["sha256"]:
                raise ValueError(f"Source hash mismatch: {source['file']}")
            path.write_bytes(data)
        if hashlib.sha256(path.read_bytes()).hexdigest() != source["sha256"]:
            raise ValueError(f"Source hash mismatch: {path}")
    css = ["/* Generated by scripts/fonts/subset.py. */"]
    report = []
    for stem, family, style in FACES:
        source = HERE / "sources" / (stem + ".woff2")
        if stem.startswith("Inter"):
            # Subsets alter Chromium metrics for advertised glyphs, even with unchanged outlines.
            path = ASSETS / source.name
            shutil.copyfile(source, path)
            for part in ("core", "extended"):
                (ASSETS / f"{stem}-{part}.woff2").unlink(missing_ok=True)
            css.append(f"""@font-face {{
\tfont-family: '{family}';
\tsrc: url('./assets/{path.name}?no-inline') format('woff2');
\tfont-style: {style};
\tfont-weight: 100 900;
\tfont-display: swap;
}}""")
            report.append({"strategy": "original", "source": inventory(source), "outputs": [inventory(path)]})
            continue
        font = TTFont(source, recalcTimestamp=False)
        original_points = set(font.getBestCmap())
        # Marks and inherited whitespace must be available in either adjacent shaping face.
        shared = {point for point in original_points if unicodedata.category(chr(point))[0] in ("M", "Z") or unicodedata.category(chr(point)) == "Cf"}
        core_points = positioning_core(font, CORE | ui_points | shared, FEATURES)
        # User content is unbounded: preserves existing coverage, including symbols and combining marks.
        if "fvar" in font:
            # The positive weight mapping is unchanged when the minimum becomes the default.
            # Reuses its original tuples: instancer rounds inferred IUP deltas (notably 0/8).
            glyf, gvar = deepcopy(font["glyf"]), deepcopy(font["gvar"])
            weight = next(axis for axis in font["fvar"].axes if axis.axisTag == "wght")
            assert weight.defaultValue == 400
            font = instantiateVariableFont(font, {"wght": (400, weight.maxValue)}, inplace=True)
            assert all(variation.axes["wght"][2] <= 0 for variations in gvar.variations.values() for variation in variations if "wght" in variation.axes and variation.axes["wght"][1] < 0)
            for glyph, variations in gvar.variations.items():
                gvar.variations[glyph] = [variation for variation in variations if variation.axes.get("wght", (0, 0, 0))[1] >= 0]
            font["glyf"], font["gvar"] = glyf, gvar
        rename(font, family, style)
        buffer = io.BytesIO()
        font.flavor = None
        font.save(buffer)
        outputs = []
        for part, points in (("extended", (original_points - core_points) | shared), ("core", core_points)):
            if not points:
                continue
            result = TTFont(io.BytesIO(buffer.getvalue()), recalcTimestamp=False)
            options = subset.Options()
            options.layout_features = sorted(FEATURES)
            # JetBrains' prep/gasp contain rasterization controls, not glyph instructions.
            options.hinting = stem.startswith("JetBrains")
            options.recalc_timestamp = False
            options.canonical_order = True
            options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14, 16, 17, 21, 22, 25]
            options.name_legacy = True
            options.name_languages = [0x409]
            sub = subset.Subsetter(options=options)
            sub.populate(unicodes=points)
            sub.subset(result)
            result.flavor = "woff2"
            path = ASSETS / f"{stem}-{part}.woff2"
            result.save(path)
            actual = TTFont(path)
            assert set(actual.getBestCmap()) == points, path
            if not options.hinting:
                assert not any(t in actual for t in ("cvt ", "fpgm", "prep")), path
            outputs.append({**inventory(path), "cssUnicodeRange": ranges(points)})
            weight = "400 800" if "fvar" in actual else "400"
            css.append(f"""@font-face {{
\tfont-family: '{family}';
\tsrc: url('./assets/{path.name}?no-inline') format('woff2');
\tfont-style: {style};
\tfont-weight: {weight};
\tfont-display: swap;
\tunicode-range: {ranges(points)};
}}""")
        (ASSETS / source.name).unlink(missing_ok=True)
        report.append({"strategy": "split", "source": inventory(source), "outputs": sorted(outputs, key=lambda output: "extended" in output["file"])})
    (ROOT / "web/src/lib/theme/font-faces.css").write_text("\n\n".join(css) + "\n")
    (HERE / "inventory.json").write_text(json.dumps(report, indent=2) + "\n")
    for face in report:
        print(face["source"]["file"], face["source"]["bytes"], "->", [f["bytes"] for f in face["outputs"]])


if __name__ == "__main__":
    main()
